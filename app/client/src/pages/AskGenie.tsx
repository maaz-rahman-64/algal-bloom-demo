import { Card, CardContent, GenieChat } from '@databricks/appkit-ui/react';
import { ExternalLink, Sparkles } from 'lucide-react';
import { useAppState } from '../AppState';

export function AskGenie() {
  const { config, officer } = useAppState();
  const openUrl =
    config?.workspaceHost && config?.genieSpaceId
      ? `${config.workspaceHost}/genie/rooms/${config.genieSpaceId}`
      : '';

  return (
    <div className="space-y-4">
      <div className="flex flex-wrap items-start justify-between gap-3">
        <div>
          <h1 className="text-2xl font-bold text-slate-900 flex items-center gap-2">
            <Sparkles className="h-5 w-5 text-[var(--brand)]" />
            Ask the data
          </h1>
          <p className="mt-1 text-sm text-slate-500">
            Ask questions about sites, samples, sonde readings and river flow in plain English.
            Answered by the <span className="font-medium">Water Quality Site Risk Explorer</span> Genie space
            {officer ? (
              <>
                {' '}· runs as <span className="font-medium">{officer.name}</span>
              </>
            ) : null}
            .
          </p>
        </div>
        {openUrl && (
          <a
            href={openUrl}
            target="_blank"
            rel="noopener noreferrer"
            className="inline-flex items-center gap-1.5 rounded-md border bg-white px-3 py-1.5 text-sm font-medium text-slate-700 hover:bg-slate-50"
          >
            Open in Databricks <ExternalLink className="h-4 w-4" />
          </a>
        )}
      </div>

      <Card className="shadow-none overflow-hidden">
        <CardContent className="p-0">
          {/* GenieChat needs an explicit height on its container. */}
          <div style={{ height: '72vh' }}>
            <GenieChat alias="default" placeholder="Ask about a site, sample, forecast, or river flow…" />
          </div>
        </CardContent>
      </Card>

      <p className="text-xs text-slate-400">
        Answers are AI-generated by Genie from the underlying Unity Catalog tables and run on behalf of the
        signed-in officer. Each answer shows the SQL it ran — verify before acting on it.
      </p>
    </div>
  );
}
